ORDER = ['1s','2s','2p','3s','3p','4s','3d','4p','5s','4d','5p','6s','4f','5d','6p','7s','5f','6d','7p']
CAP = {'s':2,'p':6,'d':10,'f':14}
def aufbau(z):
    cfg = {}; left = z
    for o in ORDER:
        if left <= 0: break
        n = min(CAP[o[1]], left); cfg[o] = n; left -= n
    return cfg
# NIST негізгі күй ерекшеліктері (толтыру ретінен ауытқитындар)
EXC = {24:{'3d':5,'4s':1},29:{'3d':10,'4s':1},41:{'4d':4,'5s':1},42:{'4d':5,'5s':1},44:{'4d':7,'5s':1},45:{'4d':8,'5s':1},46:{'4d':10,'5s':0},47:{'4d':10,'5s':1},
       57:{'4f':0,'5d':1},58:{'4f':1,'5d':1},64:{'4f':7,'5d':1},78:{'4f':14,'5d':9,'6s':1},79:{'4f':14,'5d':10,'6s':1},
       89:{'5f':0,'6d':1},90:{'5f':0,'6d':2},91:{'5f':2,'6d':1},92:{'5f':3,'6d':1},93:{'5f':4,'6d':1},96:{'5f':7,'6d':1},103:{'5f':14,'6d':0,'7p':1}}
NOBLE = [(86,'Rn'),(54,'Xe'),(36,'Kr'),(18,'Ar'),(10,'Ne'),(2,'He')]
def build(z):
    c = aufbau(z)
    if z in EXC:
        for k,v in EXC[z].items(): c[k]=v
    c = {k:v for k,v in c.items() if v>0}
    assert sum(c.values())==z, z
    return c
def fmt(z,c):
    for nz,ns in NOBLE:
        if z>nz:
            core = build(nz); rest={k:v-core.get(k,0) for k,v in c.items()}
            if all(v>=0 for v in rest.values()) and all(c.get(k,0)>=v for k,v in core.items()):
                parts=[k+str(v) for k,v in sorted(rest.items(), key=lambda kv:(int(kv[0][0]), 'spdf'.index(kv[0][1]))) if v>0]
                return f'[{ns}] ' + ' '.join(parts)
    return ' '.join(k+str(v) for k,v in sorted(c.items(), key=lambda kv:(int(kv[0][0]),'spdf'.index(kv[0][1]))))
def shells(c):
    sh=[0]*7
    for k,v in c.items(): sh[int(k[0])-1]+=v
    while sh and sh[-1]==0: sh.pop()
    return sh
def pos(z):
    # (period, group or None, row, col) кестедегі орны
    if z<=2: return (1, 1 if z==1 else 18)
    bounds=[(3,10,2),(11,18,3),(19,36,4),(37,54,5),(55,86,6),(87,118,7)]
    for a,b,p in bounds:
        if a<=z<=b:
            i=z-a
            if p in (2,3): return (p, i+1 if i<2 else i+11)
            if p in (4,5): return (p, i+1)
            # 6,7 периодтар: f-блок
            if i<2: return (p,i+1)
            if 2<=i<=16: return (p,None)   # La–Lu / Ac–Lr: f-блок жолы
            return (p, i-14+1)
out=[]
for line in ROWS.splitlines():
    z,sym,kk,en,cat,aw,awt,A,st,use=line.split('|'); z=int(z)
    c=build(z); per,grp=pos(z)
    e={'z':z,'s':sym,'kk':kk,'en':en,'cat':cat,'period':per,'group':grp,'cfg':fmt(z,c),'shells':shells(c),
       'cfgStatus':'predicted' if z>=104 else ('uncertain' if z>=100 else 'measured'),'state':st,'A':int(A),'use':use}
    if awt=='s': e['aw']=aw; e['awType']='standard'
    elif awt.startswith('i:'):
        lo,hi=awt[2:].split('-'); e['aw']=aw; e['awType']='interval'; e['interval']=[lo,hi]
    else: e['awType']='none'
    out.append(e)
assert [e['z'] for e in out]==list(range(1,119))
assert len({e['s'] for e in out})==118
